PACKS: list[dict] = []


def add(
    id: str,
    title: str,
    line: str,
    md: str,
    stations: list[str],
    exclude: list[str],
    keys: list[str],
) -> None:
    n = len(stations)
    if not (3 <= n <= 18):
        raise SystemExit(f"{id}: bad count {n}")
    PACKS.append(
        {
            "id": id,
            "title": title,
            "line": line,
            "md": md,
            "stations": stations,
            "exclude": exclude,
            "keys": keys,
        }
    )


