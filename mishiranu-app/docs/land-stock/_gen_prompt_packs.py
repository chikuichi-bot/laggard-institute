for p in PACKS:
    n = len(p["stations"])
    if not (3 <= n <= 18):
        raise SystemExit(f"bad {p['id']} count {n}: {p['stations']}")
    # no placeholders
    for s in p["stations"]:
        if "?" in s or "スキップ" in p["title"] and False:
            raise SystemExit(f"bad station in {p['id']}: {s}")


def render_pack(p: dict) -> str:
    body = COMMON.format(line=p["line"])
    excl = "\n".join(f"- {x}" for x in p["exclude"]) or "- （特になし）"
    keys = "\n".join(f"- {x}" for x in p["keys"]) or "- 同名他社駅の文をコピーしない"
    stations = " / ".join(p["stations"])
    n = len(p["stations"])
    prompt = f"""{body}
---
【{p['id']}回】{p['title']}（{n}駅）

除外（書かない）:
{excl}

キー注意:
{keys}

対象駅（この順で全部・{n}駅）:
{stations}

各駅について上記形式で書いてください。
"""
    md = f"""# {p['title']} · 土地文プロンプト（{p['id']}）

運用 B: 返ってきたら Cursor に貼る → **配線のみ**（spots しない）。

取込先: `{p['md']}` → `mishiranu-*-land-depth.ts`

---

## このまま Gemini に貼る（共通＋{p['id']}）

```
{prompt.strip()}
```
"""
    return md


