export function sentences(text: string): string[] {
  const lines: string[] = [];
  let current = "";
  for (const ch of text) {
    current += ch;
    if ("。！？".includes(ch)) {
      const t = current.trim();
      if (t) lines.push(t);
      current = "";
    }
  }
  const rest = current.trim();
  if (rest) lines.push(rest);
  return lines;
}
