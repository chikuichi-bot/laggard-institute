    /// 駅名から正本の物語のゆかりだけ取る（コイン前チラ見せ用）。
    static func notes(forName raw: String) -> [HistoryNote] {
        let bare = SavedStationStore.bareName(raw)
        guard !bare.isEmpty else { return [] }
        if let exact = byBareName[bare], !exact.isEmpty { return exact }
        return byBareName
            .filter { $0.key.count >= 3 && bare.contains($0.key) }
            .sorted { $0.key.count > $1.key.count }
            .first?
            .value ?? []
    }

    static func overlay(on station: Station) -> Station {
        let notes = notes(forName: station.name)
        guard !notes.isEmpty else { return station }
        return Station(
            id: station.id,
            name: station.name,
            nameReading: station.nameReading,
            line: station.line,
            prefecture: station.prefecture,
            region: station.region,
            mood: station.mood,
            radiiKm: station.radiiKm,
            stationIntro: station.stationIntro,
            areaAbout: station.areaAbout,
            walkGuide: station.walkGuide,
            historyNotes: station.historyNotes,
            sightseeingNotes: station.sightseeingNotes,
            storyNotes: notes,
            bikeRental: station.bikeRental,
            tourTitle: station.tourTitle,
            catchCopy: station.catchCopy,
            emptyCopy: station.emptyCopy,
            railHint: station.railHint,
            lat: station.lat,
            lng: station.lng,
            spots: station.spots,
            atmosphereCorridors: station.atmosphereCorridors
        )
    }
